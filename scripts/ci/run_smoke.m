function run_smoke
toolkit = fullfile(pwd, 'external', 'prox_crit_toolkit');
addpath(fullfile(toolkit, 'src'));
assert(strcmp(version('-release'), '2024b'), 'Expected MATLAB R2024b.');
assert(~isempty(ver('optim')), 'Optimization Toolbox is missing.');
assert(~isempty(ver('parallel')), 'Parallel Computing Toolbox is missing.');

seed = 2026;
rng(seed, 'twister');
timer = tic;
run(fullfile(toolkit, 'demo', 'smoke_demo.m'));

result = struct('experiment', 'pnas-d2-smoke', 'd2_bits_per_second', db, ...
    'exit_status', exit_status, 'ar_order', order, 'beta', b, 'samples', T, ...
    'bin_seconds', deltaT, 'seed', seed, 'fit_method', dbopt.fit_method, ...
    'ar_kernel', kern, 'innovation_sd', sigma, 'critical_kernel', kernc, ...
    'elapsed_seconds', toc(timer), 'matlab', version, 'toolboxes', ver, ...
    'project_commit', getenv('GITHUB_SHA'), 'run_id', getenv('GITHUB_RUN_ID'), ...
    'timestamp_utc', char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z''')));
mkdir('results');
writelines(string(jsonencode(result, 'PrettyPrint', true)), 'results/smoke.json');
assert(exit_status == 0 && isfinite(db) && db >= -1e-10 && ...
    all(isfinite(kern)) && isfinite(sigma) && sigma > 0, 'Official d2 smoke test failed.');
end
